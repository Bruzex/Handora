  hi,
  mr,
  ta,
  te,
  gu,
  bn;

  String get code => name;

  String get displayName => switch (this) {
    Language.en => 'English',
    Language.hi => 'हिन्दी',
    Language.mr => 'मराठी',
    Language.ta => 'தமிழ்',
    Language.te => 'తెలుగు',
    Language.gu => 'ગુજરાતી',
    Language.bn => 'বাংলা',
  };

  String get shortLabel => switch (this) {
    Language.en => 'EN',
    Language.hi => 'हिं',
    Language.mr => 'मरा',
    Language.ta => 'தமி',
    Language.te => 'తెలు',
    Language.gu => 'ગુજ',
    Language.bn => 'বাং',
  };

  bool get isIndic => this != Language.en;

  /// BCP-47 locale tag for Speech-to-Text and Text-to-Speech regional voices.
  String get localeCode => switch (this) {
    Language.en => 'en-IN',
    Language.hi => 'hi-IN',
    Language.mr => 'mr-IN',
    Language.ta => 'ta-IN',
    Language.te => 'te-IN',
    Language.gu => 'gu-IN',
    Language.bn => 'bn-IN',
  };
}

